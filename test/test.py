# TEST 2: RX
# ============================================================

@cocotb.test()
async def test_uart_rx(dut):

    dut._log.info("================================")
    dut._log.info("UART RX TEST")
    dut._log.info("================================")

    # Start 200 MHz clock
    clock = Clock(dut.clk, CLK_PERIOD_NS, unit="ns")
    cocotb.start_soon(clock.start())

    await reset_dut(dut)

    test_data = 0xA5

    # --------------------------------------------------------
    # Start monitoring RX_DONE BEFORE sending the frame
    # --------------------------------------------------------

    rx_done_event = Event()

    cocotb.start_soon(
        wait_for_rx_done(dut, rx_done_event)
    )

    # --------------------------------------------------------
    # Send UART frame
    # --------------------------------------------------------

    await send_uart_byte(dut, test_data)

    # --------------------------------------------------------
    # Wait for RX_DONE
    # --------------------------------------------------------

    try:

        await with_timeout(
            rx_done_event.wait(),
            20,
            "us"
        )

    except SimTimeoutError:

        assert False, "RX done was not asserted"

    dut._log.info("RX done detected")

    # --------------------------------------------------------
    # Read received data
    # --------------------------------------------------------

    received_data = (
        int(dut.uo_out.value) & TX_DATA_MASK
    )

    dut._log.info(
        f"RX expected = 0x{test_data:02X}"
    )

    dut._log.info(
        f"RX received = 0x{received_data:02X}"
    )

    assert received_data == test_data, (
        f"RX data incorrect: "
        f"expected 0x{test_data:02X}, "
        f"got 0x{received_data:02X}"
    )

    # --------------------------------------------------------
    # Check framing error
    # --------------------------------------------------------

    framing_error = (
        (int(dut.uio_out.value) >> FRAMING_ERROR_PIN) & 1
    )

    assert framing_error == 0, (
        "Unexpected framing error"
    )

    dut._log.info("RX test PASSED")


# ============================================================
# TEST 3: RX MULTIPLE BYTES
# ============================================================

@cocotb.test()
async def test_uart_rx_multiple_bytes(dut):

    dut._log.info("================================")
    dut._log.info("UART MULTIPLE RX TEST")
    dut._log.info("================================")

    # Start 200 MHz clock
    clock = Clock(dut.clk, CLK_PERIOD_NS, unit="ns")
    cocotb.start_soon(clock.start())

    await reset_dut(dut)

    test_values = [
        0x00,
        0x55,
        0xAA,
        0xA5,
        0xFF,
        0x42
    ]

    # --------------------------------------------------------
    # Test each byte
    # --------------------------------------------------------

    for test_data in test_values:

        dut._log.info(
            f"Testing RX value 0x{test_data:02X}"
        )

        # ----------------------------------------------------
        # Create a NEW RX_DONE monitor for this byte
        # ----------------------------------------------------

        rx_done_event = Event()

        cocotb.start_soon(
            wait_for_rx_done(dut, rx_done_event)
        )

        # ----------------------------------------------------
        # Send UART byte
        # ----------------------------------------------------

        await send_uart_byte(dut, test_data)

        # ----------------------------------------------------
        # Wait for RX_DONE
        # ----------------------------------------------------

        try:

            await with_timeout(
                rx_done_event.wait(),
                20,
                "us"
            )

        except SimTimeoutError:

            assert False, (
                f"RX done not detected for "
                f"0x{test_data:02X}"
            )

        dut._log.info(
            f"RX done detected for 0x{test_data:02X}"
        )

        # ----------------------------------------------------
        # Check received data
        # ----------------------------------------------------

        received_data = (
            int(dut.uo_out.value) & TX_DATA_MASK
        )

        dut._log.info(
            f"RX expected = 0x{test_data:02X}"
        )

        dut._log.info(
            f"RX received = 0x{received_data:02X}"
        )

        assert received_data == test_data, (
            f"RX mismatch: "
            f"expected 0x{test_data:02X}, "
            f"got 0x{received_data:02X}"
        )

        # ----------------------------------------------------
        # Check framing error
        # ----------------------------------------------------

        framing_error = (
            (int(dut.uio_out.value) >> FRAMING_ERROR_PIN) & 1
        )

        assert framing_error == 0, (
            f"Unexpected framing error for "
            f"0x{test_data:02X}"
        )

        # ----------------------------------------------------
        # Allow RX to return to IDLE
        # ----------------------------------------------------

        await ClockCycles(dut.clk, 10)

    dut._log.info(
        "Multiple RX test PASSED"
    )
